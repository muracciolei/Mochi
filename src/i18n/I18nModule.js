const SUPPORTED = ['en', 'es', 'it', 'pt', 'fr', 'de'];

export class I18nModule {
  constructor() {
    this.currentLanguage = this.detectLanguage();
  }

  /**
   * Detect best-fit language from navigator preferences.
   * Walks navigator.languages in order, falling back to navigator.language,
   * then to 'en'. Each entry's region is stripped (e.g. "pt-BR" → "pt").
   */
  detectLanguage() {
    const candidates = [];
    if (Array.isArray(navigator.languages)) {
      candidates.push(...navigator.languages);
    }
    if (navigator.language) candidates.push(navigator.language);

    for (const raw of candidates) {
      if (!raw) continue;
      const lang = String(raw).toLowerCase().split('-')[0];
      if (SUPPORTED.includes(lang)) return lang;
    }
    return 'en';
  }

  setLanguage(lang) {
    if (SUPPORTED.includes(lang)) {
      this.currentLanguage = lang;
    }
  }

  getCurrentLanguage() {
    return this.currentLanguage;
  }

  getSupportedLanguages() {
    return SUPPORTED.slice();
  }

  t(key, params = {}) {
    const translations = TRANSLATIONS[this.currentLanguage] || TRANSLATIONS.en;
    let text = translations[key];
    if (text === undefined) text = TRANSLATIONS.en[key] || key;

    if (Array.isArray(text)) {
      text = text[Math.floor(Math.random() * text.length)];
    }

    if (typeof text !== 'string') return key;

    Object.keys(params).forEach(param => {
      text = text.replace(new RegExp(`\\{${param}\\}`, 'g'), params[param]);
    });

    return text;
  }

  getDialogue(action) {
    return this.t(`dialogue.${action}`);
  }

  formatDateTime(date) {
    const options = {
      weekday: 'long', year: 'numeric', month: 'long', day: 'numeric',
      hour: '2-digit', minute: '2-digit'
    };
    const locales = {
      en: 'en-US', es: 'es-ES', it: 'it-IT',
      pt: 'pt-BR', fr: 'fr-FR', de: 'de-DE'
    };
    return date.toLocaleString(locales[this.currentLanguage] || 'en-US', options);
  }

  getDayName(date) {
    const days = {
      en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
      es: ['Domingo', 'Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes', 'Sábado'],
      it: ['Domenica', 'Lunedì', 'Martedì', 'Mercoledì', 'Giovedì', 'Venerdì', 'Sabato'],
      pt: ['Domingo', 'Segunda', 'Terça', 'Quarta', 'Quinta', 'Sexta', 'Sábado'],
      fr: ['Dimanche', 'Lundi', 'Mardi', 'Mercredi', 'Jeudi', 'Vendredi', 'Samedi'],
      de: ['Sonntag', 'Montag', 'Dienstag', 'Mittwoch', 'Donnerstag', 'Freitag', 'Samstag']
    };
    return (days[this.currentLanguage] || days.en)[date.getDay()];
  }
}
